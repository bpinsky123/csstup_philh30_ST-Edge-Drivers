local function set_nodes_status(device, value)
  local event = capabilities[capdefs.associationSet.name].associationSet({value = value})
  event.visibility = {displayed = false}
  event.state_change = true
  device:emit_component_event(device.profile.components['setAssociationGroup'], event)
end

local function pending_nodes_status(device)
  if not device:is_cc_supported(cc.WAKE_UP) then return 'Fetching nodes...' end
  if awake_sessions[device.device_network_id] then return 'Queued: fetching nodes' end
  return 'Wake device to fetch nodes'
end

local function update_queue_table(device)
  if not device.profile.components['queue'] then return end
  local this_device = device.device_network_id
  local queued_cmds
  if to_send_display[this_device] and #to_send_display[this_device] > 0 then
    local count = #to_send_display[this_device]
    local action = awake_sessions[this_device] and 'Sending' or 'Wake device to send'
    queued_cmds = string.format('%s: %d queued', action, count)
  else
    queued_cmds = 'No commands in queue'
  end
  device:emit_component_event(
    device.profile.components['queue'],
    capdefs.messageQueue.queue({value = queued_cmds}, {visibility = {displayed = false}})
  )
end

-- The hub manages the wake-up cycle. Pace pending commands and keep an
-- idle window open for follow-up requests generated by incoming reports.
local function drain_awake_queue(device, session)
  local id = device.device_network_id
  if awake_sessions[id] ~= session then return end
  local queue = to_send_queue[id] or {}
  if #queue > 0 then
    local ok, err = pcall(device.send, device, queue[1])
    if not ok then
      log.warn('Unable to send queued command; retaining it: ' .. tostring(err))
      awake_sessions[id] = nil
      update_queue_table(device)
      return
    end
    local description = to_send_display[id][1] or ''
    local group = tonumber(description:match('^Assoc Get %- Group (%d+)$') or
      description:match('^Multi%-Channel Assoc Get %- Group (%d+)$'))
    if group then
      local selected = tonumber((device:get_latest_state('setAssociationGroup', capdefs.associationGroup.name, 'associationGroup')))
      local status = device:get_latest_state('setAssociationGroup', capdefs.associationSet.name, 'associationSet')
      if group == selected and (status == 'Wake device to fetch nodes' or status == 'Queued: fetching nodes') then
        set_nodes_status(device, 'Fetching nodes...')
      end
    end
    table.remove(queue, 1)
    table.remove(to_send_display[id], 1)
    update_queue_table(device)
    device.thread:call_with_delay(1, function() drain_awake_queue(device, session) end)
  else
    local revision = session.revision
    device.thread:call_with_delay(5, function()
      if awake_sessions[id] ~= session then return end
      if revision ~= session.revision or #(to_send_queue[id] or {}) > 0 then
        drain_awake_queue(device, session)
      else
        awake_sessions[id] = nil
        log.trace('Wake-up queue dispatched; hub manages sleep')
      end
    end)
  end
end

local function send_queue(device,commands,delay,description)
  local this_device = device.device_network_id
  for _, s in ipairs(description) do
    log.trace(string.format('Queued z-wave command: %s',s))
  end
  if device:is_cc_supported(cc.WAKE_UP) then
    to_send_queue[this_device] = to_send_queue[this_device] or {}
    to_send_display[this_device] = to_send_display[this_device] or {}
    local queued = to_send_display[this_device]
    local added = 0
    local writes = false
    for _, item in ipairs(description) do
      if item:match('Assoc Remove %- Group') or item:match('Assoc Set %- Group') then writes = true; break end
    end
    for index, cmd in ipairs(commands) do
      local desc = description[index] or 'Z-Wave command'
      local is_read = desc == 'Assoc Groupings Get' or desc:match('^Assoc Get %- Group %d+$') or
        desc:match('^Multi%-Channel Assoc Get %- Group %d+$') or
        desc:match('^Assoc Group Name Get %- Group %d+$') or desc:match('^Assoc Group Info Get %- Group %d+$')
      local duplicate = false
      if is_read and not writes then for _, existing in ipairs(queued) do if existing == desc then duplicate = true; break end end end
      if not duplicate then
        table.insert(to_send_queue[this_device],cmd)
        table.insert(queued,desc)
        added = added + 1
      end
    end
    local session = awake_sessions[this_device]
    if session and added > 0 then session.revision = session.revision + 1 end
    update_queue_table(device)
  else
    delay_send(device,commands,delay)
  end
end

local function group_summary(group, data)
  local name = data.name or 'Unknown'
  local profile1 = data.profile1 and AssociationGrpInfo._reflect_profile1[data.profile1]
  local profile2_map = data.profile1 and AssociationGrpInfo._reflect_profile2[data.profile1]
  local profile2 = profile2_map and data.profile2 and profile2_map[data.profile2]
  if name == 'Unknown' and profile1 and profile2 then
    name = profile1 .. ': ' .. profile2
  end
  name = name:gsub(' control$', '')
  return string.format('%d %s', group, name)
end

local function update_group_table(device)
  local groups = associationGroups[device.device_network_id] or {}
  local group_numbers = {}
  for group, _ in pairs(groups) do
    table.insert(group_numbers, group)
  end
  table.sort(group_numbers)

  local pages = {capdefs.associationGroups.capability, capdefs.associationGroups2, capdefs.associationGroups3, capdefs.associationGroups4}
  for page, capability in ipairs(pages) do
    local first = (page - 1) * 2 + 1
    local summaries = {}
    for index = first, math.min(first + 1, #group_numbers) do
      local group = group_numbers[index]
      table.insert(summaries, group_summary(group, groups[group]))
    end
    local group_text = #summaries > 0 and table.concat(summaries, ' · ') or 'No more groups'
    if page == #pages and #group_numbers > #pages * 2 then
      group_text = string.format('%d more groups; select by number', #group_numbers - first + 1)
    end
    local evt = capability.associationGroups({value = group_text})
    evt.visibility = {displayed = false}
    device:emit_event(evt)
  end
end

local function update_device_info_table(device)
  local store = device.st_store or {}

  local function hex_or_unknown(value, width)
    return type(value) == "number" and string.format("%0" .. width .. "X", value) or "Unknown"
  end

  local function safe_text(value, fallback)
    local value_type = type(value)
    if value_type == "string" or value_type == "number" or value_type == "boolean" then
      return tostring(value)
    end
    return fallback or "Unavailable"
  end

  local diagnostic_capabilities = {
    fingerprint = capdefs.fingerprint,
    firmware = capdefs.firmware,
    security = capdefs.security,
  }
  local function emit_info(attribute, value)
    local event = diagnostic_capabilities[attribute][attribute]({value = value})
    event.visibility = {displayed = false}
    local ok, err = pcall(device.emit_event, device, event)
    if not ok then
      log.warn("Unable to emit " .. attribute .. ": " .. tostring(err))
    end
  end

  local fingerprint = hex_or_unknown(store.zwave_manufacturer_id, 4)
    .. "-" .. hex_or_unknown(store.zwave_product_type, 4)
    .. "-" .. hex_or_unknown(store.zwave_product_id, 4)

  local firmware = (store.zwave_version or {}).firmware or {}
  local firmware_text = "Unavailable"
  if firmware.major and firmware.minor then
    firmware_text = safe_text(firmware.major) .. "." .. safe_text(firmware.minor)
  end

  local security_flags = {}
  for _, flag in pairs(store.zwave_security_flags or {}) do
    if type(flag) == "string" or type(flag) == "number" then
      table.insert(security_flags, tostring(flag))
    end
  end
  local security = #security_flags > 0 and table.concat(security_flags, ", ") or "Unknown"

  emit_info("fingerprint", fingerprint)
  emit_info("firmware", firmware_text)
  emit_info("security", security)


  local node_id = tostring(device.device_network_id)
  local node_event = capdefs.nodeId.deviceNetworkId(node_id)
  local node_ok, node_err = pcall(
    device.emit_component_event,
    device,
    device.profile.components.main,
    node_event
  )
  if not node_ok then
    log.warn("Unable to emit Device Network ID: " .. tostring(node_err))
  end

  local cc_lines = {}
  for _, endpoint in ipairs(device.zwave_endpoints or {}) do
    for _, command_class in ipairs(endpoint.command_classes or {}) do
      if command_class.supported then
        local name = safe_text(cc._classes[command_class.value], "Unknown")
        log.info(string.format('Command class: %02X %s%s', command_class.value, name, command_class.secure and ' / secure' or ''))
        name = name:gsub('_', ' '):gsub('MULTI CHANNEL', 'MULTI CH'):gsub('ASSOCIATION', 'ASSOC'):gsub('MANUFACTURER', 'MFR'):gsub('FIRMWARE UPDATE', 'FW UPDATE')
        table.insert(cc_lines, string.format(
          "%02X %s%s",
          command_class.value,
          name,
          command_class.secure and " [S]" or ""
        ))
      end
    end
  end
  table.sort(cc_lines)
  local command_class_pages = {
    capdefs.commandClasses,
    capdefs.commandClasses2,
    capdefs.commandClasses3,
    capdefs.commandClasses4,
    capdefs.commandClasses5,
    capdefs.commandClasses6,
    capdefs.commandClasses7,
    capdefs.commandClasses8,
    capdefs.commandClasses9,
    capdefs.commandClasses10,
    capdefs.commandClasses11,
    capdefs.commandClasses12,
    capdefs.commandClasses13,
    capdefs.commandClasses14,
    capdefs.commandClasses15,
    capdefs.commandClasses16,
    capdefs.commandClasses17,
    capdefs.commandClasses18,
    capdefs.commandClasses19,
    capdefs.commandClasses20,
  }
  -- The mobile app may collapse newlines and truncate after two display lines.
  -- Reserve a page for any long entry; pair only compact entries.
  local pages = {}
  local index = 1
  while index <= #cc_lines do
    local first = cc_lines[index]
    local second = cc_lines[index + 1]
    local count = 1
    local value = first
    if second and #first <= 20 and #second <= 20 and #first + #second <= 36 then
      value = first .. ' · ' .. second
      count = 2
    end
    table.insert(pages, {value = value, count = count})
    index = index + count
  end
  if #pages > #command_class_pages then
    local hidden = 0
    for page = #command_class_pages, #pages do hidden = hidden + pages[page].count end
    pages[#command_class_pages] = {value = string.format('%d more: see driver logs', hidden)}
    log.warn(string.format('Command class display omitted %d entries; full list logged', hidden))
  end
  for page, capability in ipairs(command_class_pages) do
    local value = pages[page] and pages[page].value or 'No additional command classes'
    local command_class_event = capability.commandClasses({value = value})
    command_class_event.visibility = {displayed = false}
    local classes_ok, classes_err = pcall(device.emit_event, device, command_class_event)
    if not classes_ok then
      log.warn("Unable to emit command classes page " .. page .. ": " .. tostring(classes_err))
    end
  end
end

-- Fingerprint matching is not sufficient on every hub. Reconcile the profile
-- against the command classes actually reported by this device.
local PROFILE_PENDING = 'utility_profile_pending'
local function ensure_profile(device)
  local components = device.profile.components
  local supports_association = not not device:is_cc_supported(cc.ASSOCIATION)
  local sleepy = not not device:is_cc_supported(cc.WAKE_UP)
  local has_association_controls = components['setAssociationGroup'] ~= nil
  local has_queue = components['queue'] ~= nil
  if supports_association ~= has_association_controls or sleepy ~= has_queue then
    local profile = supports_association and (sleepy and 'associate-me-sleepy' or 'associate-me')
      or (sleepy and 'thing-sleepy' or 'thing')
    if device:get_field(PROFILE_PENDING) ~= profile then
      device:set_field(PROFILE_PENDING, profile)
      device:try_update_metadata({profile = profile})
    end
    return false
  end
  return true
end

--- @param driver st.zwave.Driver
--- @param device st.zwave.Device
local function init(driver, device)
  if device:is_cc_supported(cc.WAKE_UP) then
    update_queue_table(device)
    if device.profile.components['setAssociationGroup'] and #(to_send_queue[device.device_network_id] or {}) == 0 then
      local status = device:get_latest_state('setAssociationGroup', capdefs.associationSet.name, 'associationSet')
      if status == 'Wake device to fetch nodes' or status == 'Queued: fetching nodes' or status == 'Fetching nodes...' then
        set_nodes_status(device, 'Select a group to fetch nodes')
      end
    end
  end
  local ok, err = pcall(update_device_info_table, device)
  if not ok then
    log.warn(string.format("Unable to update device information: %s", tostring(err)))
  end
  if ensure_profile(device) and device:is_cc_supported(cc.ASSOCIATION) and not initial_scans[device.device_network_id] then
    initial_scans[device.device_network_id] = true
    device:refresh()
  end
end

local function info_changed(driver, device)
  if ensure_profile(device) and device:get_field(PROFILE_PENDING) then
    device:set_field(PROFILE_PENDING, nil)
    device:refresh()
  end
end

